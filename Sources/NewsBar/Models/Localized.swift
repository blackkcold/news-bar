import Foundation

/// Lightweight localization helper for a SwiftPM package (no `.xcstrings` bundle).
/// `AppSettings` keeps `currentLanguage` in sync so both SwiftUI views and
/// services (notifications, orchestrator errors) resolve the same language.
enum L10n {
    static var currentLanguage: AppLanguage = .zh

    static func string(_ key: String, language: AppLanguage? = nil) -> String {
        let lang = language ?? currentLanguage
        let table = lang == .en ? enStrings : zhStrings
        return table[key] ?? key
    }

    static func string(_ key: String, language: AppLanguage? = nil, _ args: CVarArg...) -> String {
        let format = string(key, language: language)
        return String(format: format, locale: Locale(identifier: language?.bcp47 ?? currentLanguage.bcp47), arguments: args)
    }

    /// Test-only view of the two tables so a missing translation is a test
    /// failure instead of a raw key in the UI.
    static var keyParity: (missingInEnglish: Set<String>, missingInChinese: Set<String>) {
        (
            Set(zhStrings.keys).subtracting(enStrings.keys),
            Set(enStrings.keys).subtracting(zhStrings.keys)
        )
    }

    /// Test-only: every defined key, for the "used but undefined" lint.
    static var allKeys: Set<String> { Set(zhStrings.keys) }

    /// Test-only: the Chinese format strings, for the format-contract test.
    static var testFormats: [String: String] { zhStrings }

